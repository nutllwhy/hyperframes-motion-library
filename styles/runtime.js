/* Authored for this project. Embedded into each standalone composition by sync-styles.mjs. */
(function () {
  "use strict";
  const catalog = window.__motionStyleCatalog;
  const schema = JSON.parse(document.documentElement.getAttribute("data-composition-variables") || "[]");
  const defaults = Object.fromEntries(schema.map((field) => [field.id, field.default]));
  const originalGetVariables = window.__hyperframes?.getVariables?.bind(window.__hyperframes);
  const query = new URLSearchParams(window.location.search);
  const preview = query.get("motionPreview") === "1";
  let supplied = originalGetVariables ? originalGetVariables() : {};
  if (preview) {
    try { supplied = JSON.parse(query.get("variables") || "{}"); }
    catch { throw new Error("风格预览参数不是有效 JSON"); }
  }
  const styleId = supplied.styleId || catalog.defaultStyleId;
  const pack = catalog.styles.find((style) => style.id === styleId);
  if (!pack) throw new Error(`未知画面风格：${styleId}`);
  const values = { ...defaults, ...supplied, styleId };
  if (styleId !== catalog.defaultStyleId) {
    for (const field of schema.filter((item) => item.type === "color")) {
      const token = field.id === "bg" ? "background" : field.id;
      if (pack.tokens[token] && (!supplied[field.id] || supplied[field.id].toUpperCase() === String(field.default).toUpperCase())) values[field.id] = pack.tokens[token];
    }
    if (typeof defaults.colors === "string" && (!supplied.colors || supplied.colors === defaults.colors)) {
      values.colors = defaults.colors.split(",").map((color) => color.trim().toUpperCase() === String(defaults.accent).toUpperCase() ? values.accent : pack.tokens.line).join(",");
    }
  }
  window.__hyperframes = window.__hyperframes || {};
  window.__hyperframes.getVariables = () => ({ ...values });
  document.documentElement.dataset.motionStyle = styleId;
  document.documentElement.dataset.exportMode = values.exportMode || "transparent";
  for (const [key, value] of Object.entries(pack.tokens)) document.documentElement.style.setProperty(`--style-${key}`, value);
  const colors = { foreground: values.foreground || pack.tokens.foreground, background: values.background || values.bg || pack.tokens.background, accent: values.accent || pack.tokens.accent };
  for (const [key, value] of Object.entries(colors)) {
    document.documentElement.style.setProperty(`--style-${key}`, value);
    document.documentElement.style.setProperty(`--${key}`, value);
  }
  document.documentElement.style.setProperty("--fg", colors.foreground);
  document.documentElement.style.setProperty("--style-on-accent", styleId === "bold-geometry" ? "#191715" : "#FFFCF3");
  document.documentElement.style.setProperty("--style-heading-font", pack.typography.heading);
  document.documentElement.style.setProperty("--style-body-font", pack.typography.body);
  document.documentElement.style.setProperty("--style-number-font", pack.typography.numeric);

  const roles = {
    heading: ".title,.headline,.prefix,.term,.keyword,.step-title,.option-title,.fact-text,.myth-text,.claim,.quote",
    number: ".value,.score,.stat-value,.no,.no-text",
    body: ".caption,.note,.desc,.definition,.subtitle,.option-detail,.meaning,.source,.byline,.author,.name,.tag,.connector-word,.point,.tick-label,.bar-label,.y-label,.x-label",
    badge: ".eyebrow,.kicker,.meta,.label,.tag,.index,.no,.desc-tag,.verdict,.conclusion,.takeaway",
    surface: ".box,.option,.step,.myth-card,.fact-card,.quote-panel,.card,.panel,.marker,.cluster,.list .item",
    frame: ".card,.panel,.comparison-panel,.counter-panel,.content,.statement,.compare,.loop,.layout,.stack,.cluster",
    line: ".rule,.rail,.rail-fill,.divider,.return-path,.line,.line-path,.footer-rule,.scan,.bar",
    track: ".track,.ring-track,.meter",
    decorative: ".glow,.halo,.sheen,.burst"
  };
  function markRoles() {
    for (const [role, selector] of Object.entries(roles)) {
      document.querySelectorAll(selector).forEach((node) => {
        const current = new Set((node.dataset.styleRole || "").split(" ").filter(Boolean));
        current.add(role);
        node.dataset.styleRole = [...current].join(" ");
      });
    }
    // In these templates .label is the actual title, rather than a small label chip.
    if (document.querySelector(".comparison-panel,.hero .label")) {
      document.querySelectorAll(".comparison-panel > .label,.hero .label").forEach((node) => { node.dataset.styleRole = "heading"; });
    }
    document.querySelectorAll(".point,.option-detail").forEach((node) => { node.dataset.styleRole = "accent-fill"; });
    if (document.querySelector(".meter")) document.querySelectorAll(".caption").forEach((node) => { node.dataset.styleRole = "badge accent-fill"; });
    // Chart text is generated by its template script and must follow the same ink palette.
    if (styleId !== catalog.defaultStyleId) {
      document.querySelectorAll("svg text").forEach((node) => {
        node.style.fill = node.classList.contains("bar-value") ? colors.foreground : pack.tokens.muted;
        node.style.fontFamily = pack.typography.body;
      });
      document.querySelectorAll(".grid-line-elem,.baseline").forEach((node) => { node.style.stroke = pack.tokens.line; });
      document.querySelectorAll(".bar-rect").forEach((node) => {
        node.setAttribute("rx", "0");
        if (styleId === "sketch-notes") {
          node.style.stroke = colors.accent;
          node.style.strokeWidth = "3";
          node.style.strokeDasharray = "8 3";
          node.style.fillOpacity = ".65";
        }
      });
    }
  }
  markRoles();
  window.MotionStyles = {
    id: styleId,
    values,
    ease(original) {
      if (styleId === catalog.defaultStyleId || original === "none" || original === "linear") return original;
      if (styleId === "sketch-notes") return "steps(12)";
      if (original.includes("inOut")) return styleId === "paper-editorial" ? "power2.inOut" : "expo.inOut";
      if (original.endsWith(".in")) return styleId === "paper-editorial" ? "power2.in" : "expo.in";
      return pack.motion.ease;
    },
    finish(timeline) {
      markRoles();
      if (preview) {
        const play = () => { if (timeline) timeline.repeat(100).play(0); };
        if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", play, { once: true });
        else play();
      }
    }
  };
})();
