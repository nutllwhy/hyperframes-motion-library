import fs from "node:fs/promises";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { getTemplate, readVariableSchema, resolveStyleVariables, resolveVariants, root, templateOrientations } from "./library.js";

const args = process.argv.slice(2);
const styleArg = args.find((arg) => arg.startsWith("--style="))?.slice("--style=".length);
const orientation = args.includes("--portrait") ? "portrait" : "landscape";
const unknownFlag = args.find((arg) => arg.startsWith("--") && !arg.startsWith("--style=") && arg !== "--portrait");
if (unknownFlag) throw new Error(`未知选项：${unknownFlag}`);
const [templateId, presetArg, formatArg = "mp4", outputBaseArg] = args.filter((arg) => !arg.startsWith("--"));
if (!templateId) throw new Error("用法：npm run render -- <template-id> [preset.json] [mp4|webm] [输出文件名] [--style=<风格ID>] [--portrait]");
const template = await getTemplate(templateId);
if (!templateOrientations(template).includes(orientation)) throw new Error(`模板 ${templateId} 没有${orientation === "portrait" ? "竖屏" : "横屏"}版本`);
const renderRoot = path.join(template.absolutePath, resolveVariants(template)[orientation].path || "");
const format = ["mp4", "webm"].includes(formatArg) ? formatArg : "mp4";
const presetPath = presetArg ? path.resolve(root, presetArg) : path.join(template.absolutePath, "presets/default.json");
const values = JSON.parse(await fs.readFile(presetPath, "utf8"));
const schema = await readVariableSchema(renderRoot);
const styledValues = await resolveStyleVariables(schema, values, styleArg);
const renderValues = schema.some((item) => item.id === "exportMode") ? { ...styledValues, exportMode: format === "mp4" ? "mp4" : "transparent" } : styledValues;
const outputDir = path.join(root, "renders", templateId);
await fs.mkdir(outputDir, { recursive: true });
const styleSuffix = styledValues.styleId === "classic-orange" ? "" : `-${styledValues.styleId}`;
const outputBase = outputBaseArg || `${orientation === "portrait" ? "portrait-" : ""}${path.basename(presetPath, ".json")}${styleSuffix}`;
const output = path.join(outputDir, `${outputBase}.${format}`);
const result = spawnSync("npx", ["--yes", "hyperframes@0.6.115", "render", "--format", format, "--strict-variables", "--variables", JSON.stringify(renderValues), "--output", output], { cwd: renderRoot, stdio: "inherit" });
process.exit(result.status || 0);
